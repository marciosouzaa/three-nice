import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

await mkdir('artifacts', { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('console', (message) => {
    if (message.type() === 'error') errors.push(message.text())
  })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/particulas')
  await page.locator('.is-ready').waitFor()
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(1500)
  await page.screenshot({ path: 'artifacts/particles-sphere.png' })
  await page.mouse.move(960, 450)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/particles-galaxy.png' })
  await page.mouse.move(960, 880)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/particles-waves.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await page.locator('.is-ready').waitFor()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/particles-mobile.png' })
  await page.getByRole('link', { name: 'Maré', exact: true }).click()
  await page.locator('.mare-experience.is-ready').waitFor()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/collection-mare-mobile.png' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/collection-mare.png' })
  await page.getByRole('link', { name: 'Líquido', exact: true }).click()
  await page.locator('.liquid-experience.is-ready').waitFor()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/liquid-desktop.png' })
  await page.mouse.move(240, 140)
  await page.waitForTimeout(2000)
  await page.screenshot({ path: 'artifacts/liquid-cold.png' })
  await page.mouse.move(1150, 780)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/liquid-hot.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await page.locator('.liquid-experience.is-ready').waitFor()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/liquid-mobile.png' })
  await page.getByRole('link', { name: 'Planeta', exact: true }).click()
  await page.locator('.planet-experience.is-ready').waitFor()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/planet-mobile.png' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/planet-day.png' })
  await page.mouse.move(1050, 885)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/planet-night.png' })
  await page.mouse.move(300, 150)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/planet-rotated.png' })
  await page.getByRole('link', { name: 'Túnel', exact: true }).click()
  await page.locator('.tunnel-experience.is-ready').waitFor()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/tunnel-desktop.png' })
  await page.mouse.move(1150, 150)
  await page.waitForTimeout(2000)
  await page.screenshot({ path: 'artifacts/tunnel-fast.png' })
  await page.mouse.move(250, 890)
  await page.waitForTimeout(2000)
  await page.screenshot({ path: 'artifacts/tunnel-slow.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.reload()
  await page.locator('.tunnel-experience.is-ready').waitFor()
  await page.waitForTimeout(1000)
  await page.screenshot({ path: 'artifacts/tunnel-mobile.png' })
  console.log(
    JSON.stringify({
      errors,
      path: new URL(page.url()).pathname,
      canvasCount: await page.locator('canvas').count(),
    }),
  )
} finally {
  await browser.close()
}
